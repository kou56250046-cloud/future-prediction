/**
 * 見方タブの本文。
 * @param {{ renderedIds: Iterable<string> }} opts 今回のビルドで実際に出たブロックの id
 */
export function guideBody({ renderedIds }) {
  const rendered = new Set(renderedIds);

  const intro = section({
    id: 'guide-purpose',
    title: 'このページは何か',
    body: `<p>AI の進化と IT 関連職のニーズの変化を定点観測し、<strong>自分の予測をベースラインと比べて採点する</strong>ためのページです。</p>
<p>予測は確率つきで登録し、期日に機械で判定します。現状維持（いまの値が続く）と直線外挿（いまの傾きが続く）の両方に勝てていなければ、その予測は「できている」とは言いません。グラフはそのための材料で、眺めて納得するためのものではありません。</p>
<p>タブは3つです。</p>
<ul>
<li><a href="#dashboard">ダッシュボード</a> — 採点結果とデータの推移</li>
<li><a href="#skill-outlook">スキル解説</a> — スキルごとの変化の分類と、今後の見立て</li>
<li><a href="#guide">見方</a> — このタブ。各ブロックの読み方と用語</li>
</ul>`,
  });

  const blockRows = BLOCKS.map((b) => {
    // 補足文は見出しの外に置く。見出しの中に入れると、見出し一覧で読み上げられるノイズになる
    const heading = rendered.has(b.id)
      ? `<h3><a href="#${esc(b.id)}">${esc(b.title)}</a></h3>`
      : `<h3>${esc(b.title)}</h3>\n<p class="footnote">判定済みの予測ができると表示される</p>`;
    return `<div class="guide-block">
${heading}
<dl>
<dt>何を見るか</dt><dd>${esc(b.what)}</dd>
<dt>どう読むか</dt><dd>${esc(b.how)}</dd>
<dt>よくある誤読</dt><dd>${esc(b.trap)}</dd>
</dl>
</div>`;
  }).join('\n');

  const blocks = section({
    id: 'guide-blocks',
    title: 'ダッシュボードの各ブロック',
    sub: '上から並んでいる順。見出しを押すとそのブロックへ移る',
    body: blockRows,
  });

  const glossary = section({
    id: 'guide-glossary',
    title: '用語',
    body: `<div class="scroll">${table(['用語', '意味'], GLOSSARY)}</div>`,
  });

  const limits = section({
    id: 'guide-limits',
    title: 'データの限界',
    sub: '知っていないと誤読する性質',
    body: `<div class="scroll">${table(['性質', '内容'], LIMITS)}</div>`,
    footnote: 'データ品質ブロックが悪化しているときは、他のグラフを信用しない',
  });

  const ops = section({
    id: 'guide-ops',
    title: '更新と予測の登録',
    body: `<div class="scroll">${table(['コマンド', 'すること'], COMMANDS.map(([c, d]) => [{ html: `<code>${esc(c)}</code>` }, d]))}</div>
<p class="footnote">予測の書き方の例は <code>node scripts/predict-add.js --example</code>、指標名の検索は <code>node scripts/predict-add.js --metrics jobs.skill</code>。</p>`,
  });

  return [intro, blocks, glossary, limits, ops].join('\n');
}
